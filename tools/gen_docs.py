#!/usr/bin/env python3
"""
gen_docs.py - generate the reference docs that must never drift from the data.

Writes:
  docs/DATA_DICTIONARY.md  one row per indicator: id, label, unit, kind, frequency, source table,
                           latest reading, definition source  (the file consumers read)
  docs/DEFINITIONS.md      every sourced definition with its publisher and URL

Both are produced from dashboard/warroom_data.json, so they are regenerated by the daily workflow and
by CI whenever the dataset changes. Hand-editing them is pointless - the next run overwrites them.

STETP: [INFO]/[WARN]/[ERROR] logs, granular try/except, non-zero exit on failure.
"""
from __future__ import annotations

import datetime as dt
import json
import logging
import pathlib
import sys
import traceback

logging.basicConfig(level=logging.INFO, format="%(message)s", stream=sys.stderr)
log = logging.getLogger("gendocs")

ROOT = pathlib.Path(__file__).resolve().parents[1]
GENERATED_NOTE = ("<!-- GENERATED FILE - produced by tools/gen_docs.py from the built dataset. "
                  "Do not edit by hand: the next refresh overwrites it. -->")


def freq_of(points: list) -> str:
    try:
        ds = sorted(dt.date.fromisoformat(p[0]) for p in points)
        if len(ds) < 3:
            return "unknown"
        gaps = sorted((ds[i + 1] - ds[i]).days for i in range(len(ds) - 1))
        med = gaps[len(gaps) // 2]
        return ("daily" if med <= 3 else "weekly" if med <= 9 else "fortnightly" if med <= 20
                else "monthly" if med <= 45 else "quarterly" if med <= 120 else "irregular")
    except Exception:
        log.warning("[WARN] [Freq] could not derive frequency for a series")
        return "unknown"


def main() -> int:
    try:
        payload = json.loads((ROOT / "dashboard" / "warroom_data.json").read_text())
        series, defs = payload["series"], payload.get("definitions") or {}
        as_of, generated = payload["as_of"], payload["generated"]

        # ---------- DATA_DICTIONARY.md ---------------------------------------------------------
        lines = [GENERATED_NOTE, "", "# Data dictionary", "",
                 f"**{len(payload['tiles'])} indicators** · dataset as-of **{as_of}** · "
                 f"generated {generated}", "",
                 "Every series is derived from a published RBI table; `kind` distinguishes a policy "
                 "**setting** (a rate that changes occasionally, dated by when it took effect) from a "
                 "**reading** (an observation dated by the period it covers). Values are in the unit "
                 "shown; growth rates are year-on-year per cent unless stated otherwise.", "",
                 "Machine-readable equivalents: `api/v1/index.json` (catalogue), "
                 "`api/v1/series/<id>.json` (full history), `api/v1/series/<id>.csv` (CSV).", ""]
        group = None
        for t in sorted(payload["tiles"], key=lambda x: (x["group"], x["id"])):
            if t["group"] != group:
                group = t["group"]
                lines += ["", f"## {group}", "",
                          "| id | indicator | unit | kind | frequency | latest | as at | source table | definition |",
                          "|---|---|---|---|---|---:|---|---|---|"]
            d = defs.get(t["def_key"]) or {}
            freq = t.get("freq") or freq_of(series[t["series_key"]]["points"])
            val = t["value"]
            # 4dp, then strip trailing zeros. Two decimals truncated the published value: the data
            # dictionary said 95.07 for USD/INR while the API and its CSV both said 95.0691, and this
            # file's own contract is that it "must never drift" from the API.
            val_s = f"{val:,.4f}".rstrip("0").rstrip(".") if isinstance(val, float) else str(val)
            stale = " *(stale)*" if t.get("stale") else ""
            lines.append(
                f"| `{t['id']}` | {t['label']} | {t['unit']} | "
                f"{'setting' if t.get('step') else 'reading'} | {freq} | {val_s}{stale} | "
                f"{t['period']} | {series[t['series_key']].get('source','')} | "
                f"[{d.get('term','—')}]({d.get('source_url','#')}) |")
        (ROOT / "docs" / "DATA_DICTIONARY.md").write_text("\n".join(lines) + "\n")

        # ---------- DEFINITIONS.md -------------------------------------------------------------
        lines = [GENERATED_NOTE, "", "# Sourced definitions", "",
                 f"All {len(defs)} terms used by the dashboard and API, quoted from the publishing "
                 "agency. Nothing here is written from memory: if a term has no sourced wording it is "
                 "omitted, and the UI shows \"definition pending\" instead.", "",
                 "Machine-readable: `api/v1/definitions.json`.", ""]
        for key in sorted(defs):
            d = defs[key]
            lines += [f"## {d.get('term', key)}", "", d.get("definition", ""), "",
                      f"**Source:** {d.get('source_name','—')} — <{d.get('source_url','')}>", "",
                      f"<sub>key: `{key}`</sub>", ""]
        (ROOT / "docs" / "DEFINITIONS.md").write_text("\n".join(lines) + "\n")

        log.info("[INFO] [Docs] wrote docs/DATA_DICTIONARY.md (%s indicators) and docs/DEFINITIONS.md "
                 "(%s definitions)", len(payload["tiles"]), len(defs))
        return 0
    except Exception:
        log.error("[ERROR] [Docs] generation failed:\n%s", traceback.format_exc())
        return 1


if __name__ == "__main__":
    sys.exit(main())
